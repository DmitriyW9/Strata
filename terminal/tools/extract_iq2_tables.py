#!/usr/bin/env python3
# terminal/tools/extract_iq2_tables.py - read the four IQ2 lookup tables out of ggml-common.h and write them
# as a plain python module (terminal/tools/iq2_tables.py) that terminal/tools/naive_iq2.py imports.
#
# These tables are the IQ2 codebook: FORMAT DATA, not a formula.  Strata's engine reads the very same
# tables through ggml's compiled `to_float` (docs/NAIVE.md); this file copies them so the independent
# numpy reference in naive_iq2.py decodes the same codebook rather than a re-derived one.  The table
# CONTENT is therefore shared by construction and is NOT what the numpy/C++ cross-check proves (that
# proves the element mapping, sign and scale application).  We extract rather than retype so a ggml
# version bump that edits a codebook is picked up, not silently diverged from.
#
#   python terminal/tools/extract_iq2_tables.py [ggml-common.h] [iq2_tables.py]
#
# Each table is a `GGML_TABLE_BEGIN(type, name, size) ... GGML_TABLE_END()` block whose body is a
# comma-separated list of integer literals (possibly hex).  We take the named block, strip comments,
# and parse the integers.  A sanity pass checks each count and a few spot values, so a parser that
# grabbed the wrong block or truncated a list fails loudly instead of writing a wrong codebook.

from __future__ import annotations

import pathlib
import re
import sys

DEFAULT_HDR = ("/home/dmitriy/projects/ai/LLM/Strata/third_party/strata-ggml/ggml/src/ggml-common.h")
DEFAULT_OUT = str(pathlib.Path(__file__).resolve().with_name("iq2_tables.py"))

TABLES = ["kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid"]
EXPECT = {"kmask_iq2xs": 8, "ksigns_iq2xs": 128, "iq2xxs_grid": 256, "iq2xs_grid": 512}


def extract(text: str, name: str) -> list[int]:
    # The block starts at `GGML_TABLE_BEGIN(<type>, name, size)` (two spellings of the macro exist
    # under different include guards) and ends at the first GGML_TABLE_END() after it.
    start = None
    for m in re.finditer(r"GGML_TABLE_BEGIN\s*\([^)]*\b" + re.escape(name) + r"\s*,\s*\d+\s*\)", text):
        start = m.end()
        break
    if start is None:
        raise SystemExit(f"no GGML_TABLE_BEGIN block for {name}")
    end = text.index("GGML_TABLE_END", start)
    body = text[start:end]
    body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)      # drop any block comments
    toks = [t for t in re.split(r"[,\s]+", body.strip()) if t]
    vals = [int(t, 0) for t in toks]                        # int(...,0) handles 0x.. hex
    if len(vals) != EXPECT[name]:
        raise SystemExit(f"{name}: parsed {len(vals)} values, expected {EXPECT[name]}")
    return vals


def main() -> None:
    hdr = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_HDR)
    out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT)
    text = hdr.read_text()
    data = {name: extract(text, name) for name in TABLES}

    # Spot checks that pin the extraction to the right rows (from ggml-common.h as of this checkout):
    # kmask is the eight powers of two; the first grid entry is all-0x08 (the "flat smallest" codeword).
    assert data["kmask_iq2xs"] == [1, 2, 4, 8, 16, 32, 64, 128], "kmask_iq2xs is not powers of two"
    assert data["ksigns_iq2xs"][0] == 0 and data["ksigns_iq2xs"][-1] == 255, "ksigns endpoints"
    assert data["iq2xxs_grid"][0] == 0x0808080808080808, "iq2xxs_grid[0]"
    assert data["iq2xs_grid"][0] == 0x0808080808080808, "iq2xs_grid[0]"
    # iq2xxs_grid and iq2xs_grid share their first 8 codewords in ggml-common.h (both start flat).
    assert data["iq2xxs_grid"][:5] == data["iq2xs_grid"][:5], "the two grids disagree at entry 0-4"

    lines = ["#!/usr/bin/env python3",
             "# terminal/tools/iq2_tables.py - GENERATED by terminal/tools/extract_iq2_tables.py from ggml-common.h.",
             "# The IQ2 codebook (format data).  Do not edit by hand; re-run the extractor.",
             ""]
    for name in TABLES:
        lines.append(f"{name} = [")
        vals = data[name]
        for i in range(0, len(vals), 8):
            lines.append("    " + " ".join(f"0x{v:x}, " for v in vals[i:i + 8]).rstrip())
        lines.append("]")
        lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out.name}: " + ", ".join(f"{n}={len(data[n])}" for n in TABLES))


if __name__ == "__main__":
    main()
